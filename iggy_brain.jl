# TIER 3 — Flux legacy (iggy_speak.jl)
# ─────────────────────────────────────────

function call_flux_model(input::String; len=200, temp=1.2, penalty=15.0) :: String
    isfile(BRAIN_PATH) || return (
        "I am IGGY. No local model. Set OPENROUTER_API_KEY (Tier 1) " *
        "or run: pip install torch transformers datasets peft (Tier 2).")
    try
        @eval using Flux, Serialization, StatsBase
        id_to_char, char_to_id = get_vocab_local()
        isempty(id_to_char) && return "IGGY: SovereignData empty."
        model = deserialize(BRAIN_PATH)
        sc = isempty(input) ? 'I' : input[1]
        Flux.reset!(model)
        buf = Char[]; cur = [get(char_to_id, sc, 1);;]; hist = Int[]
        for _ in 1:len
            logits = vec(model(cur))
            for id in unique(hist[max(1,end-20):end])
                logits[id] -= penalty
            end
            probs = exp.((logits .- maximum(logits)) ./ temp)
            probs ./= sum(probs)
            try
                nid = StatsBase.sample(1:length(probs), StatsBase.Weights(probs))
                push!(buf, get(id_to_char, nid, ' ')); push!(hist, nid)
                cur = [nid;;]
            catch; cur = [rand(1:length(logits));;]; end
        end
        return String(buf)
    catch e
        return "Flux error: $(typeof(e))"
    end
end

function get_vocab_local()
    isdir(DATA_PATH) || return Dict{Int,Char}(), Dict{Char,Int}()
    raw = ""
    for f in readdir(DATA_PATH)
        (endswith(f,".txt")||endswith(f,".jl")) || continue
        try; raw *= read(joinpath(DATA_PATH,f), String); catch; end
    end
    isempty(raw) && return Dict{Int,Char}(), Dict{Char,Int}()
    uc = sort(collect(Set(raw)))
    return Dict(i=>c for (i,c) in enumerate(uc)),
           Dict(c=>i for (i,c) in enumerate(uc))
end

