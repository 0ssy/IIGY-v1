function store_to_knowledge_base(text::String; source::String = "iggy")
    load_pycall!() || return
    try; _py_store[](text, source); catch; end
end

# ─────────────────────────────────────────
# VISION CONTEXT
# Called by iggy_vision.jl after every screenshot
# ─────────────────────────────────────────

function iggy_process_vision(screen_description::String)
    ts = Dates.format(now(), "HH:MM:SS")
    remember!(IGGY_MEMORY, "system", "[Screen @ $ts]: $screen_description")
    queue_for_training(screen_description;            source="vision")
    store_to_knowledge_base(screen_description;       source="screen@$ts")
    println("👁  Vision logged: $(first(screen_description, 80))...")
end

# ─────────────────────────────────────────
# URL + FILE LEARNING
# ─────────────────────────────────────────

function iggy_learn_url(url::String) :: String
    try
        res = HTTP.get(url; status_exception=false)
        res.status == 200 || return "Could not fetch $url (status $(res.status))"
        raw  = String(res.body)
        text = strip(replace(replace(raw, r"<[^>]+>" => " "), r"\s+" => " "))
        text = text[1:min(3000,length(text))]
        summary = iggy_think("Summarize key facts in 5 bullets.\nURL: $url\n\n$text")
        remember!(IGGY_MEMORY, "system", "Learned from $url:\n$summary")
        store_to_knowledge_base(summary; source=url)
        queue_for_training("URL: $url\nSummary: $summary"; source="url_learn")
        return summary
    catch e
        return "Error fetching $url: $(typeof(e))"
    end
end

function iggy_learn_file(path::String) :: String
    isfile(path) || return "File not found: $path"
    try
        content = let _s = replace(read(path, String), "\r\n" => "\n", "\r" => "\n"); _s[1:nextind(_s, 0, min(4000, length(_s)))]; end
        summary = iggy_think("Summarize key info in 5 bullets.\nFile: $path\n\n$content")
        remember!(IGGY_MEMORY, "system", "Learned from $path:\n$summary")
        store_to_knowledge_base(content; source=path)
        queue_for_training("FILE: $path\n$content"; source="file_learn")
        return summary
    catch e
        return "Error reading $path: $(typeof(e))"
    end
end

