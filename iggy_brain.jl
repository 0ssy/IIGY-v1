function iggy_analyze_trade(;
        symbol::String, side::String,
        entry::Float64, exit_price::Float64,
        pnl::Float64,  indicators::String = "") :: String

    outcome = pnl > 0 ? "WIN (+$(round(pnl*100,digits=3))%)" :
              pnl < 0 ? "LOSS ($(round(pnl*100,digits=3))%)" : "SCRATCH"

    prompt = """
Post-trade analysis:
Symbol: $symbol | Side: $side | Entry: $entry | Exit: $exit_price | $outcome
Indicators: $indicators

Answer in under 80 words:
1. Why did this trade $(pnl > 0 ? "win" : "lose")?
2. What market condition caused this?
3. ONE rule IGGY should remember (start with "RULE:").
"""
    msgs = Dict{String,String}[
        Dict("role"=>"system","content"=>build_system_prompt()),
        Dict("role"=>"user",  "content"=>prompt)
    ]
    response = call_openrouter(msgs; model=OR_QUANT_MODEL, max_tokens=220)
    response === nothing && (response = call_tinyllama(prompt; max_tokens=220))
    response === nothing && (response = "Analysis unavailable — no brain tier active.")

    # Extract and persist learned rule
    for line in split(response, "\n")
        if occursin("RULE:", line)
            rule = strip(replace(line, r"^.*RULE:\s*" => ""))
            if length(rule) > 10
                save_insight!(rule)
                println("💡 Insight saved: $rule")
                # Queue conversation for LoRA training
                queue_for_training("$prompt\n\nIGGY: $response"; source="trade_analysis")
            end
            break
        end
    end

    return response
end

