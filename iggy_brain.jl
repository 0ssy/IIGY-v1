function call_openrouter(messages::Vector{Dict{String,String}};
                         model::String = OR_CHAT_MODEL,
                         max_tokens::Int = 512) :: Union{String,Nothing}
    isempty(get_or_key()) && return nothing
    try
        res = HTTP.post(
            OR_API_URL,
            ["Content-Type" => "application/json",
             "Authorization" => "Bearer $(get_or_key())",
             "HTTP-Referer"  => "https://github.com/0ssy/IIGY-v1",
             "X-Title"       => "IGGY"],
            JSON.json(Dict("model"=>model,"max_tokens"=>max_tokens,"messages"=>messages));
            status_exception=false
        )
        res.status == 200 || return nothing
        data = JSON.parse(String(res.body))
        return strip(string(data["choices"][1]["message"]["content"]))
    catch
        return nothing
    end
end

