"""
    iggy_think(user_input; trade_context="", screen_context="") → String

Main entry point for all conversation. Called by bridge and executive.
Automatically selects the best available brain tier.
"""
function iggy_think(user_input::String;
                    trade_context::String  = "",
                    screen_context::String = "") :: String

    intent = detect_intent(user_input)

    # ── Tier 1: OpenRouter ────────────────────────────────────────────────────
    if !isempty(get_or_key())
        msgs = Dict{String,String}[Dict("role"=>"system","content"=>build_system_prompt())]
        if !isempty(trade_context) && intent in (:trading,:quant_analysis)
            push!(msgs, Dict("role"=>"system","content"=>"Live trading context:\n$trade_context"))
        end
        !isempty(screen_context) && push!(msgs,
            Dict("role"=>"system","content"=>"Screen context:\n$screen_context"))
        append!(msgs, IGGY_MEMORY.history)
        push!(msgs, Dict("role"=>"user","content"=>user_input))

        model    = intent == :quant_analysis ? OR_QUANT_MODEL : OR_CHAT_MODEL
        response = call_openrouter(msgs; model=model, max_tokens=600)
        if response !== nothing
            remember!(IGGY_MEMORY, "user",      user_input)
            remember!(IGGY_MEMORY, "assistant", response)
            store_to_knowledge_base(user_input*"\n"*response; source="conversation")
            return response
        end
        println("⚡ OpenRouter unavailable — falling to Tier 2.")
    end

    # ── Tier 2: TinyLlama ────────────────────────────────────────────────────
    ctx = join(filter(!isempty,[trade_context, screen_context]), "\n")
    response = call_tinyllama(user_input; screen_context=ctx, max_tokens=400)
    if response !== nothing
        remember!(IGGY_MEMORY, "user",      user_input)
        remember!(IGGY_MEMORY, "assistant", response)
        return response
    end
    println("⚡ TinyLlama unavailable — falling to Tier 3 (Flux).")

    # ── Tier 3: Flux legacy ───────────────────────────────────────────────────
    response = call_flux_model(user_input)
    remember!(IGGY_MEMORY, "user",      user_input)
    remember!(IGGY_MEMORY, "assistant", response)
    return response
end

