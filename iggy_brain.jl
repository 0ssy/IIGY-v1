function detect_intent(input::String) :: Symbol
    lower = lowercase(input)
    any(w -> occursin(w, lower),
        ["trade","position","pnl","profit","loss","btc","eth","sol",
         "balance","drawdown","buy","sell","long","short","signal",
         "indicator","market","chart","price","portfolio"])  && return :trading
    any(w -> occursin(w, lower),
        ["screen","see","vision","watch","look","saw",
         "screenshot","display","app","window"])             && return :vision
    any(w -> occursin(w, lower),
        ["why did","why was","analyze","analyse","post-trade",
         "review","what went wrong","what worked"])          && return :quant_analysis
    return :general
end

